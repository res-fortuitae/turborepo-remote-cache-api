const result = Bun.spawnSync(
  [
    "bun",
    "x",
    "auth",
    "generate",
    "--config",
    "./scripts/auth-schema.config.ts",
    "--output",
    "./src/schema/auth.ts",
    "--adapter",
    "drizzle",
    "--dialect",
    "sqlite",
    "--yes",
  ],
  { stdout: "inherit", stderr: "inherit" },
);

if (result.exitCode !== 0) process.exit(result.exitCode);

// Better Auth 1.7 emits the Drizzle 0.x relations API. Retain generated tables;
// DatabaseLive builds the Drizzle 1.x relations from the complete schema instead.
const file = Bun.file("./src/schema/auth.ts");
const generated = await file.text();

if (
  !generated.startsWith('import { relations, sql } from "drizzle-orm";') ||
  !generated.includes("export const userRelations =")
) {
  throw new Error("Better Auth generator changed; review Drizzle 1.x normalization");
}

await Bun.write(
  file,
  "// Generated by bun run db:auth:generate (Better Auth 1.7); do not edit.\n" +
    generated
      .replace("import { relations, sql }", "import { sql }")
      .split("export const userRelations =")[0],
);

const formatted = Bun.spawnSync(["bun", "x", "oxfmt", "--write", "./src/schema/auth.ts"], {
  stdout: "inherit",
  stderr: "inherit",
});

if (formatted.exitCode !== 0) process.exit(formatted.exitCode);
